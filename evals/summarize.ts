/**
 * Turns promptfoo JSON output into `evals/results.md`: pass rate per eval category and per metric,
 * token totals, latency, and a per-case table. Usage: `tsx evals/summarize.ts [files...]`.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";

type CaseResult = {
  success: boolean;
  latencyMs?: number;
  error?: string;
  testCase: { description?: string; metadata?: { category?: string } };
  response?: { tokenUsage?: { total?: number }; metadata?: { threadId?: string; fellBack?: boolean } };
  gradingResult?: {
    componentResults?: Array<{ pass: boolean; reason?: string; assertion?: { metric?: string; type?: string } }>;
  };
  provider?: { label?: string; id?: string };
};

const files = process.argv.slice(2).length
  ? process.argv.slice(2)
  : ["evals/output/live.json", "evals/output/components.json"].filter((file) => existsSync(file));

if (!files.length) {
  console.error("No promptfoo output found. Run `pnpm eval:live` first.");
  process.exit(1);
}

const cases: Array<CaseResult & { suite: string }> = [];
for (const file of files) {
  const json = JSON.parse(readFileSync(file, "utf8"));
  const suite = String(json.config?.description ?? file);
  for (const result of json.results?.results ?? []) cases.push({ ...result, suite });
}

const pct = (pass: number, total: number) => (total ? `${Math.round((pass / total) * 100)}%` : "n/a");
const tally = new Map<string, { pass: number; total: number }>();
const metrics = new Map<string, { pass: number; total: number }>();
for (const item of cases) {
  const category = item.testCase.metadata?.category ?? "other";
  const bucket = tally.get(category) ?? { pass: 0, total: 0 };
  bucket.total += 1;
  if (item.success) bucket.pass += 1;
  tally.set(category, bucket);
  for (const component of item.gradingResult?.componentResults ?? []) {
    const metric = component.assertion?.metric ?? component.assertion?.type ?? "other";
    const entry = metrics.get(metric) ?? { pass: 0, total: 0 };
    entry.total += 1;
    if (component.pass) entry.pass += 1;
    metrics.set(metric, entry);
  }
}

const latencies = cases.map((item) => item.latencyMs ?? 0).sort((a, b) => a - b);
const p50 = latencies[Math.floor(latencies.length / 2)] ?? 0;
const p95 = latencies[Math.min(latencies.length - 1, Math.floor(latencies.length * 0.95))] ?? 0;
const tokens = cases.reduce((sum, item) => sum + (item.response?.tokenUsage?.total ?? 0), 0);
const passed = cases.filter((item) => item.success).length;

const failureReason = (item: CaseResult) =>
  item.error ??
  item.gradingResult?.componentResults
    ?.filter((component) => !component.pass)
    .map((component) => component.reason ?? "")
    .join("; ")
    .replace(/\s+/g, " ")
    .slice(0, 160) ??
  "";

const lines = [
  "# Eval results",
  "",
  `Last live run: ${new Date().toISOString().slice(0, 10)}. Generated by \`evals/summarize.ts\` from \`pnpm eval:live\`.`,
  "Deterministic suite (`pnpm eval`) runs in CI on every push and is not included here.",
  "",
  `**${passed}/${cases.length} cases passed (${pct(passed, cases.length)})** · agent tokens ${tokens.toLocaleString("en-US")} (judge tokens not counted) · latency p50 ${(p50 / 1000).toFixed(1)}s, p95 ${(p95 / 1000).toFixed(1)}s per case`,
  "",
  "## By eval type",
  "",
  "| Category | Passed | Rate |",
  "|---|---|---|",
  ...[...tally.entries()].sort().map(([name, { pass, total }]) => `| ${name} | ${pass}/${total} | ${pct(pass, total)} |`),
  "",
  "## By assertion metric",
  "",
  "| Metric | Passed | Rate |",
  "|---|---|---|",
  ...[...metrics.entries()].sort().map(([name, { pass, total }]) => `| ${name} | ${pass}/${total} | ${pct(pass, total)} |`),
  "",
  "## Cases",
  "",
  "| Suite | Case | Result | Latency | LangSmith thread | Failure reason |",
  "|---|---|---|---|---|---|",
  ...cases.map(
    (item) =>
      `| ${item.provider?.label ?? item.suite} | ${item.testCase.description ?? ""} | ${item.success ? "pass" : "**fail**"} | ${((item.latencyMs ?? 0) / 1000).toFixed(1)}s | \`${item.response?.metadata?.threadId ?? "-"}\` | ${item.success ? "" : failureReason(item).replace(/\|/g, "\\|")} |`,
  ),
  "",
];

writeFileSync("evals/results.md", lines.join("\n"));
console.log(`Wrote evals/results.md (${passed}/${cases.length} passed)`);
